import json
import unicodedata
import re

def normalize(c):
    # quitar tildes y espacios extras
    c = ''.join(x for x in unicodedata.normalize('NFD', c) if unicodedata.category(x) != 'Mn')
    c = c.upper().strip()
    c = re.sub(r'\s+', ' ', c)
    # clean weird chars
    c = c.replace('"', 'Ñ').replace('\'', 'Ñ')
    return c

